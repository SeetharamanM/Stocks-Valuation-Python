"""End-to-end run: no API key, no network, real spreadsheet.

Guards the whole pipeline shape and the two properties that matter most for
trustworthiness: the report opens offline, and every figure in it is traceable
to the arithmetic rather than asserted by prose.
"""

import os
import re

import pytest

from src.analyst import run_analysis
from src.report import render_report
from src.screener_parser import parse_screener
from src.web_data import MarketData


@pytest.fixture(scope="module")
def result():
    fin = parse_screener("Aurionpro Sol.xlsx")
    md = MarketData(ticker="AURIONPRO", price=735.4, market_cap=4076.37,
                    low_52w=500.0, high_52w=1650.0, beta=0.9, as_of="2026-07-27",
                    source={k: "manual" for k in
                            ("price", "market_cap", "low_52w", "high_52w", "beta")})
    return run_analysis(fin, md, "non-financial", 0.069, 0.055)


@pytest.fixture(scope="module")
def report(result, tmp_path_factory):
    out = os.path.join(tmp_path_factory.mktemp("report"), "Aurionpro_Valuation.html")
    render_report(result, out)
    return out, open(out, encoding="utf-8").read()


def test_end_to_end_produces_report(report, result):
    out, html = report
    assert os.path.getsize(out) > 200_000, "Chart.js should be inlined"
    assert "AURIONPRO" in html and result["rating"] in html
    assert html.count('class="tab-btn') == 11
    assert "Not investment advice" in html


def test_report_opens_offline(report):
    """Nothing may be *loaded* from the network. URLs inside the bundled
    Chart.js licence banner are inert text, so match on the loading constructs
    rather than on the substring "http"."""
    lowered = report[1].lower()
    for external in ('src="http', "src='http", 'src="//', "@import",
                     "<link", 'href="http', "url(http"):
        assert external not in lowered, f"external resource load found: {external}"


def test_every_panel_carries_both_commentary_and_computed_figures(report):
    html = report[1]
    panels = re.split(r'<section class="panel', html)[1:]
    assert len(panels) == 11
    for i, panel in enumerate(panels, 1):
        assert '<div class="narrative">' in panel
        body = panel.split('<div class="narrative">', 1)[1]
        assert len(body) > 400, f"panel {i} is close to empty"


def test_the_report_says_how_it_was_made(report):
    html = report[1]
    assert "no language model was involved" in html
    assert "Nothing here is generated by a language model" in html


def test_the_verdict_in_the_masthead_matches_the_computed_figures(report, result):
    html = report[1]
    assert f'<div class="rating">{result["rating"]}</div>' in html
    assert f'Conviction: {result["conviction"]}' in html
    assert f'₹{result["fair_value"]:,.0f}' in html


def test_the_headline_fair_value_is_the_triangulation_blend(result):
    """The masthead figure must be the weighted blend, not a number chosen
    independently of the method table beneath it."""
    assert result["fair_value"] == result["triangulation"]["blended"]


def test_the_target_price_is_the_scenario_expected_value(result):
    assert result["target_price"] == result["scenario"]["expected_value"]


def test_no_placeholder_zeros_reach_the_report(result):
    for method in result["triangulation"]["methods"]:
        assert method["value"] != 0
    for s in result["scenario"]["scenarios"]:
        assert s["value"] != 0


def test_every_disclosed_assumption_appears_somewhere_in_the_report(report, result):
    """An assumption the reader cannot find is no better than a hidden one."""
    html = report[1]
    a = result["assumptions"]
    assert f'{a["terminal_growth"] * 100:.1f}%' in html
    assert "self-funding ceiling" in html
    assert "stated prior" in html          # scenario probabilities
    assert "Base weight for a non-financial business" in html
