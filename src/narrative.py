# 2 — Valuation Base
# ---------------------------------------------------------------------------

def s2(result):
    b = result["pack"]["base"]
    eps_fy, eps_ttm = b.get("eps_latest_fy"), b.get("eps_ttm")
    conv, tax = b.get("fcf_pat_conversion"), b.get("effective_tax_rate")
    net_cash = b.get("net_cash")

    if eps_fy and eps_ttm:
        drift = eps_ttm / eps_fy - 1
        direction = "ahead of" if drift > 0.02 else ("behind" if drift < -0.02 else "in line with")
        earnings = (
            f"Trailing-twelve-month EPS of {rs(eps_ttm)} runs {direction} the "
            f"FY{b.get('latest_fy')} figure of {rs(eps_fy)} ({signed_pct(drift)}). Every "
            "multiple in Section 3 is struck on the audited full-year EPS, not the TTM "
            "figure, so the comparison against history stays like-for-like.")
    else:
        earnings = ("The earnings base could not be assembled from both the annual and the "
                    "quarterly statements; the multiples that follow use whichever of the two "
                    "was available, as labelled.")

    if conv is None:
        cash = ("Free-cash-flow conversion could not be computed, because the five-year cash-flow "
                "and balance-sheet series do not overlap far enough to estimate capex from "
                "fixed-asset movement. Read the DCF in Section 5 with that gap in mind.")
    elif conv < 0:
        cash = (
            f"Free cash flow has converted {pct(conv)} of reported profit over the last five "
            "years — that is, the company has consumed cash across the period rather than "
            "generated it, even while reporting profits. This is the single most consequential "
            "figure in the report. It is not automatically damning: a business part-way through "
            "a capital programme looks exactly like this, and Section 5 fades capex toward "
            "depreciation over the forecast rather than assuming the current intensity persists. "
            "But that fade is an assumption, and it is the one carrying most of the valuation. "
            "If the spending does not normalise, the DCF here is too generous by a wide margin.")
    elif conv < FCF_CONVERSION_HEALTHY:
        cash = (
            f"Free cash flow has converted {pct(conv)} of reported profit over the last five "
            f"years, below the {pct(FCF_CONVERSION_HEALTHY)} that would mark comfortable "
            "conversion. That is the single most consequential input in this report: profits "
            "that do not turn into cash cannot be discounted as if they had. Section 5 fades "
            "capex toward depreciation over the forecast rather than assuming the current "
            "intensity persists, which is the assumption most worth arguing with.")
    else:
        cash = (
            f"Free cash flow has converted {pct(conv)} of reported profit over the last five "
            f"years, at or above the {pct(FCF_CONVERSION_HEALTHY)} mark. Earnings are backed by "
            "cash, so the earnings-based methods in Section 7 and the cash-flow model in "
            "Section 5 are measuring broadly the same thing.")

    if tax is None:
        tax_txt = "The effective tax rate could not be computed for the latest year."
    elif tax < TAX_CONCESSION_LEVEL:
        tax_txt = (
            f"The effective tax rate of {pct(tax)} sits materially below the 25.17% statutory "
            "rate. The forecast does not assume the concession is permanent: it fades the rate "
            "to statutory across the five explicit years, which lowers modelled NOPAT relative "
            "to a flat-rate forecast. If the benefit is in fact structural, this model is "
            "conservative by that margin.")
    else:
        tax_txt = (f"The effective tax rate of {pct(tax)} is close to the 25.17% statutory rate, "
                   "so no material tax normalisation is being carried by the forecast.")

    if net_cash is None:
        balance = ""
    elif net_cash >= 0:
        balance = (f"The company carries net cash of {rs(net_cash, 0)} Cr, which is added back in "
                   "the bridge from enterprise value to equity value in Section 5 and leaves "
                   "balance-sheet capacity for the capex path the forecast assumes.")
    else:
        balance = (f"The company carries net debt of {rs(-net_cash, 0)} Cr, deducted in the "
                   "enterprise-to-equity bridge in Section 5. Leverage raises the sensitivity of "
                   "the per-share answer to the discount rate, which Section 10 quantifies.")

    limits = (
        "Two limits of this data set are disclosed rather than worked around. Capex is not "
        "reported separately in the source, so it is estimated from the movement in net block "
        "and capital work-in-progress; and the change in working capital is not derivable at "
        "all, so it is carried as a stated assumption in the forecast. Neither is a reported "
        "figure and neither should be read as one. Exceptional-item normalisation, tangible "
        "book value and ESOP-adjusted share counts are not separable from this export either, "
        "so reported PAT is used unadjusted — where a company has recurring exceptionals, that "
        "flatters every earnings-based method here.")

    return paras(earnings, cash, tax_txt, balance, limits)


