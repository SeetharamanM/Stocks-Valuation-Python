def _grid_swing(d):
    """Fair-value impact of a one-point move in WACC and in terminal growth,
    read off the sensitivity grid's centre cell and its neighbours.
    """
    grid = d.get("sensitivity_grid") or {}
    cells, waccs, gs = grid.get("grid"), grid.get("waccs"), grid.get("gs")
    if not (cells and waccs and gs):
        return None
    ci, cj = len(waccs) // 2, len(gs) // 2
    base = cells[ci][cj]
    if not base:
        return None
    out = {"base": base}
    up = cells[ci + 1][cj] if ci + 1 < len(waccs) else None
    if up:
        out["wacc_plus_1"] = up / base - 1
    g_up = cells[ci][cj + 1] if cj + 1 < len(gs) else None
    if g_up:
        out["g_plus_1"] = g_up / base - 1
    return out


def s10(result):
    pack, sc = result["pack"], result["scenario"]
    d = pack["dcf"]
    ranked = []

    swing = _grid_swing(d) if d.get("viable") else None
    if swing and "wacc_plus_1" in swing:
        ranked.append(("Discount rate (WACC)",
                       f"A one-percentage-point rise in WACC moves the DCF fair value by "
                       f"{signed_pct(swing['wacc_plus_1'])}. WACC is built on an assumed 9% "
                       "pre-tax cost of debt and a supplied risk-free rate and equity risk "
                       "premium — none of them read from the statements.",
                       abs(swing["wacc_plus_1"])))
    if swing and "g_plus_1" in swing:
        ranked.append(("Terminal growth",
                       f"A one-percentage-point rise in terminal growth moves the DCF fair value "
                       f"by {signed_pct(swing['g_plus_1'])}. Terminal growth is capped by rule at "
                       "the lowest of long-run GDP, the self-funding ceiling and WACC less two "
                       "points, so the downside on this input is better controlled than the "
                       "upside.",
                       abs(swing["g_plus_1"])))

    rows = [s for s in (sc.get("scenarios") or []) if s.get("value") is not None]
    if len(rows) >= 2 and d.get("viable"):
        vals = [s["value"] for s in rows]
        base_v = next((s["value"] for s in rows if s.get("name") == "Base"), None)
        if base_v:
            spread = (max(vals) - min(vals)) / base_v
            ranked.append(("Operating delivery — revenue growth and EBIT margin",
                           f"Shifting growth and margin by the company's own historical "
                           f"dispersion moves the fair value across a range {pct(spread)} as wide "
                           "as the base case. This is operating risk — whether the business "
                           "performs — as distinct from the modelling risk carried by the "
                           "discount rate and the terminal assumption.",
                           spread))

    ranked.sort(key=lambda x: -x[2])
    shown = ranked[:3]
    if shown:
        count = {1: "assumption", 2: "two assumptions", 3: "three assumptions"}[len(shown)]
        listed = (f"<b>The {count} this valuation is most sensitive to, ranked by measured "
                  "impact on the fair value.</b><ol>" +
                  "".join(f"<li><b>{esc(n)}.</b> {t}</li>" for n, t, _ in shown) + "</ol>")
    else:
        listed = ("The fair value's sensitivity could not be quantified, because the DCF is not "
                  "viable and no sensitivity grid was produced. The dominant risk is therefore "
                  "the one named in Section 5: the model that would normally carry the answer "
                  "could not be anchored at all.")

    data_risk = (
        "<b>Data risks specific to this run.</b> Capex is estimated from fixed-asset movement "
        "rather than reported, so a year of disposals, revaluations or reclassification "
        "distorts it. The change in working capital is not derivable from this export and is "
        "carried as a flat assumption. Reported PAT is used without stripping exceptional items. "
        "Any of these being materially wrong moves the fair value more than a rating change would.")

    invalidation = (
        "<b>What would invalidate the thesis.</b> Two consecutive full-year results in which "
        "revenue growth or EBIT margin falls outside the bear-case path in Section 8; a capex "
        "programme that does not fade toward depreciation as the forecast assumes; an equity "
        "raise, which would confirm that the growth being priced cannot be self-funded; or a "
        "sustained fall in return on invested capital, which lowers the self-funding ceiling that "
        "Section 6 tests the price against. These are observable events, not concerns.")

    sector_risk = (
        "<b>Not covered here.</b> Sector, regulatory and competitive risks that would compress "
        "the multiple are not modelled, because they cannot be derived from financial statements. "
        "They are real and they are absent from every number in this report.")

    return listed + paras(data_risk, invalidation, sector_risk)


