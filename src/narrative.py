"""Deterministic commentary for the eleven report sections.

This module replaces the language-model narrative pass. Every sentence is
assembled from figures the Python engine already computed, and every branch is
driven by a threshold that is stated in the sentence it produces. The result is
prose that is boring by design: it can be re-derived from the pack by hand, and
it cannot introduce a number that the arithmetic does not support.

Three rules hold throughout:

* No figure is formatted here by hand — everything goes through `src.fmt`, so a
  missing value renders as the disclosure string instead of a blank or a zero.
* No sentence asserts something the data does not show. Where an input is
  unavailable the text says so and gives the qualitative read instead, which is
  what SAFARI_Valuation.txt asks for.
* The commentary never repeats the computed tables that follow it in the same
  panel; it interprets them.
"""

from src.fmt import esc, mult, num, paras, pct, rs, signed_pct

# Thresholds that shape the wording. Each one is quoted in the sentence it
# drives, so the reader can disagree with the threshold rather than guess it.
FCF_CONVERSION_HEALTHY = 0.70
TAX_CONCESSION_LEVEL = 0.22
BAND_STRETCHED_SD = 1.0
TERMINAL_VALUE_LIMIT = 0.70


def _h(text):
    return f"<h3>{text}</h3>"


# ---------------------------------------------------------------------------
# 1 — Valuation Snapshot
# ---------------------------------------------------------------------------

def s1(result):
    pack, v = result["pack"], result["verdict"]
    meta = pack["meta"]
    price = meta.get("current_price")
    tri = result["triangulation"]
    zone = v.get("accumulation_zone")

    zone_str = (f"{rs(zone['low'], 0)} – {rs(zone['high'], 0)}"
                if zone else "not derivable — no blended fair value")

    box = paras(
        f"<b>Recommendation:</b> {esc(v['rating'])} &nbsp;·&nbsp; "
        f"<b>Fair value:</b> <u>{rs(v.get('fair_value'), 0)}</u> &nbsp;·&nbsp; "
        f"<b>Target price:</b> <u>{rs(v.get('target_price'), 0)}</u> "
        f"({signed_pct(v.get('implied_move'))}) &nbsp;·&nbsp; "
        f"<b>Accumulation zone:</b> {zone_str} &nbsp;·&nbsp; "
        f"<b>Horizon:</b> {esc(v['horizon'])} &nbsp;·&nbsp; "
        f"<b>Conviction:</b> {esc(v['conviction'])} — {esc(v['conviction_detail']['reason'])}")

    gap = None
    if v.get("fair_value") and price:
        gap = v["fair_value"] / price - 1

    if gap is None:
        verdict = ("No blended fair value could be computed from the supplied statements, so "
                   "no gap between price and value is asserted here. Sections 2 to 6 set out "
                   "what could be computed and what could not.")
    elif gap > 0:
        verdict = (
            f"At {rs(price)} the market is paying less than this model's blended fair value of "
            f"{rs(v['fair_value'], 0)}, a gap of {signed_pct(gap)}. That blend spans "
            f"{rs(tri.get('low'), 0)} to {rs(tri.get('high'), 0)} across the methods that could "
            "be computed, and the width of that range — not the point estimate — is the honest "
            "statement of how much of this is knowable. The scenario work in Section 8 tests "
            "whether the gap survives the downside as well as the upside.")
    else:
        verdict = (
            f"At {rs(price)} the market is paying more than this model's blended fair value of "
            f"{rs(v['fair_value'], 0)}, a gap of {signed_pct(gap)}. The methods that could be "
            f"computed span {rs(tri.get('low'), 0)} to {rs(tri.get('high'), 0)}; the price sits "
            "toward or above the upper end of what the company's own economics currently "
            "support, so the case rests on delivery beyond the disclosed driver path.")

    engine = (
        "Every figure in this report is computed in Python from the supplied statements and "
        "market data. The forecast drivers, terminal growth, scenario shocks and method "
        "weights are produced by stated rules — set out where each is used — rather than by "
        "judgement applied case by case. Nothing here is generated by a language model.")

    return box + paras(verdict, engine)


