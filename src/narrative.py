# 7 — Triangulation
# ---------------------------------------------------------------------------

def s7(result):
    tri, a = result["triangulation"], result["assumptions"]
    detail = a.get("triangulation_detail") or {}
    blended, lo, hi = tri.get("blended"), tri.get("low"), tri.get("high")

    lead = (
        f"The methods that could be computed blend to <b>{rs(blended, 0)}</b> per share. The "
        "weights are set by rule, not by preference: each business type starts from a fixed "
        "weighting, and that weighting is then adjusted for what this particular data set will "
        "support. The table below shows each weight with the rule that produced it.")

    adjustments = detail.get("adjustments") or []
    if adjustments:
        adjust = ("<b>Adjustments applied to the base weights.</b> " +
                  " ".join(esc(x) for x in adjustments))
    else:
        adjust = ("<b>No adjustments were needed.</b> The base weights for this business type "
                  "were applied unchanged: no method failed to compute, the terminal value stayed "
                  "within its threshold, and the P/E history was long enough to use.")

    if lo is not None and hi is not None and blended:
        width = (hi - lo) / blended
        band = (
            f"Method outputs span {rs(lo, 0)} to {rs(hi, 0)}, a range {pct(width)} as wide as the "
            "blend itself. That range is the honest statement of confidence here. A narrow band "
            "means the methods agree and the answer is robust to which one you prefer; a wide one "
            "means the blend is an average of disagreeing views, and position size should reflect "
            "that rather than the neatness of the single number.")
    else:
        band = ""

    dropped = tri.get("dropped") or []
    drop_txt = (
        "<b>Methods excluded:</b> " + esc(", ".join(str(d) for d in dropped)) +
        ". These could not be computed from the supplied data and were dropped with the "
        "remaining weights renormalised, rather than being counted as zero — which would have "
        "dragged the blend toward a value nobody modelled." if dropped else "")

    return paras(lead, adjust, band, drop_txt)


# ---------------------------------------------------------------------------
# 8 — Scenario Analysis
# ---------------------------------------------------------------------------

def s8(result):
    sc, a = result["scenario"], result["assumptions"]
    pack = result["pack"]
    price = pack["meta"].get("current_price")
    detail = a.get("scenario_detail") or {}
    rows = sc.get("scenarios") or []

    method = ("<b>How the scenarios were built.</b> " + esc(detail.get("method") or "")
              if detail.get("method") else "")

    ev = sc.get("expected_value")
    if ev is None:
        payoff = ("No scenario could be valued, so no expected value is offered. See the note on "
                  "each row below for why.")
    elif price:
        values = [s["value"] for s in rows if s.get("value") is not None]
        bear, bull = min(values), max(values)
        down, up = bear / price - 1, bull / price - 1
        asym = abs(up) / abs(down) if down else None
        if asym is None:
            shape = "."
        elif asym >= 1.5:
            shape = (f". The upside is {num(asym, 1)} times the downside in magnitude — a "
                     "favourably asymmetric payoff, which is worth more than a high base case.")
        elif asym <= 0.8:
            shape = (f". The downside is {num(1 / asym, 1)} times the upside in magnitude — an "
                     "adversely asymmetric payoff. You are being asked to risk more than you "
                     "stand to make, which is the argument against the position regardless of "
                     "where the expected value lands.")
        else:
            shape = (f". Upside and downside are of similar magnitude ({num(asym, 1)}× ), so the "
                     "payoff offers no asymmetry to lean on either way.")
        payoff = (
            f"The probability-weighted expected value is {rs(ev, 0)}, {signed_pct(sc.get('upside_pct'))} "
            f"against the current price. The bear case is worth {rs(bear, 0)} ({signed_pct(down)}) "
            f"and the bull case {rs(bull, 0)} ({signed_pct(up)}){shape}"
            " The question is not what the stock is worth if things go well, but what it costs "
            "you if they do not.")
    else:
        payoff = (f"The probability-weighted expected value is {rs(ev, 0)}. No current price was "
                  "available, so no move against price is stated.")

    honesty = (
        "The probabilities are a stated prior, not a measurement. Nothing in a set of financial "
        "statements tells you how likely a future is, and this model does not pretend otherwise: "
        f"it assigns {pct(0.25, 0)} / {pct(0.50, 0)} / {pct(0.25, 0)} to bear, base and bull "
        "as a convention. If you hold a different view of the odds, the expected value moves "
        "linearly with it — the scenario values themselves are unaffected.")

    dropped = sc.get("dropped") or []
    drop_txt = ("<b>Scenarios excluded from the expected value:</b> " +
                esc(", ".join(str(d) for d in dropped)) +
                ". These could not be valued and the surviving probabilities were renormalised."
                if dropped else "")

    return paras(method, payoff, honesty, drop_txt)


