# 6 — Reverse DCF (the most important paragraph)
# ---------------------------------------------------------------------------

def s6(result):
    pack = result["pack"]
    r, ret = pack.get("reverse_dcf") or {}, pack["returns"]
    if not r.get("available"):
        return paras(
            "The reverse DCF could not be run, because it needs a viable forward model to "
            "invert. No implied growth rate has been invented in its place. Without it, the "
            "central question of this report — whether what the market is paying for is "
            "achievable — cannot be answered quantitatively from this data set.")

    implied = r.get("growth")
    sgr, groic = ret.get("sgr"), ret.get("g_from_reinvestment")
    cands = [x for x in (sgr, groic) if x is not None]
    ceiling = min(cands) if cands else None

    lead = (
        f"<b>At the current price the market is implying revenue growth of {pct(implied)} a year "
        "across the explicit forecast</b>, holding margins, capex intensity, WACC and terminal "
        "growth at the levels used in Section 5. That is the single number this whole report "
        "turns on: it is what has to be true for today's price to be right.")

    if ceiling is None:
        verdict = ("The self-funding ceiling could not be computed, so the implied rate cannot be "
                   "tested against what the company can finance. Read the figure above as "
                   "unbenchmarked.")
    else:
        gap = implied - ceiling
        if gap > 0.03:
            verdict = (
                f"Against a self-funding ceiling of {pct(ceiling)} — the lower of a sustainable "
                f"growth rate of {pct(sgr)} and reinvestment × ROIC of {pct(groic)} — this is a "
                f"<b>heroic</b> expectation. The market is paying for {pct(gap)} a year more "
                "growth than the company can finance out of retained earnings at its current "
                "returns on capital. Delivering it requires external equity, more debt, or a "
                "structural improvement in ROIC. None of those is free, and none is in the price.")
        elif gap > 0:
            verdict = (
                f"Against a self-funding ceiling of {pct(ceiling)} — the lower of a sustainable "
                f"growth rate of {pct(sgr)} and reinvestment × ROIC of {pct(groic)} — this is "
                f"<b>demanding but not heroic</b>. The implied rate is {pct(gap)} above what "
                "retained earnings can fund, a gap small enough to be closed by a modest "
                "improvement in returns or a lower payout, but it does have to be closed.")
        elif gap > -0.03:
            verdict = (
                f"Against a self-funding ceiling of {pct(ceiling)} — the lower of a sustainable "
                f"growth rate of {pct(sgr)} and reinvestment × ROIC of {pct(groic)} — this is an "
                "<b>achievable</b> expectation. The market is not paying for growth that has to "
                "be financed from outside the business, so the argument here is about delivery "
                "rather than about arithmetic possibility.")
        else:
            verdict = (
                f"Against a self-funding ceiling of {pct(ceiling)} — the lower of a sustainable "
                f"growth rate of {pct(sgr)} and reinvestment × ROIC of {pct(groic)} — this is a "
                f"<b>conservative</b> expectation. The price implies {pct(-gap)} a year less "
                "growth than the company can self-fund at current returns. Either the market "
                "doubts those returns persist, or there is a gap between price and value here.")

    bound = ""
    if r.get("out_of_bounds"):
        bound = (f"The solver hit its {esc(r.get('bound_hit'))} bound, so the figure above is a "
                 "limit rather than a point estimate: read it as 'at least' or 'at most'. The "
                 "true implied rate lies outside the range the solver searches, which itself "
                 "says the price is a long way from what the model supports.")

    caveat = (
        "One caveat on method: the solve moves revenue growth only, holding every other driver "
        "fixed. In reality a company that grows faster usually also spends more capex and "
        "carries more working capital, so a like-for-like implied rate would be a little higher "
        "than the figure above.")

    return paras(lead, verdict, bound, caveat)


