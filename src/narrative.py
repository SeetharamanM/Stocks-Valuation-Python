def s3(result):
    pack = result["pack"]
    rel, bands, ret = pack["relative"], pack["bands"], pack["returns"]
    pe, med5, med10 = bands.get("current_pe"), bands.get("median_pe_5y"), bands.get("median_pe_10y")

    if pe is None or med5 is None:
        placement = ("The current P/E could not be placed against the company's own history: "
                     "one or both of the current multiple and the five-year median is "
                     "unavailable. The table below shows what could be computed.")
    else:
        prem5 = pe / med5 - 1
        word = "a premium of" if prem5 > 0 else "a discount of"
        placement = (
            f"The stock trades at {mult(pe)} earnings against its own five-year median of "
            f"{mult(med5)} — {word} {pct(abs(prem5))}"
            + (f", and {mult(med10)} on ten years" if med10 is not None else "") + ".")

    roe, roic = ret.get("roe"), ret.get("roic")
    if pe is not None and med5 is not None and roe is not None:
        prem5 = pe / med5 - 1
        if prem5 > 0.10:
            justify = (
                f"A premium to its own history is justified only by a durable improvement in "
                f"growth, returns or risk. Return on equity currently runs {pct(roe)} and return "
                f"on invested capital {pct(roic)}; the question the reverse DCF in Section 6 "
                "answers is whether the growth the premium implies can be financed out of those "
                "returns. If it cannot, the premium is an expectation rather than a valuation.")
        elif prem5 < -0.10:
            justify = (
                f"A discount to its own history is only an opportunity if the economics have not "
                f"deteriorated with it. Return on equity of {pct(roe)} and return on invested "
                f"capital of {pct(roic)} are the test: a de-rating that tracks falling returns on "
                "capital is the market repricing a worse business, not mispricing the same one.")
        else:
            justify = (
                f"The stock is trading close to its own recent rating, so relative valuation is "
                f"not making the case either way here. Return on equity of {pct(roe)} and return "
                f"on invested capital of {pct(roic)} set the ceiling on what growth can be "
                "self-financed, which is where Section 6 picks the argument up.")
    else:
        justify = ("Returns on capital could not be computed alongside the multiples, so no "
                   "premium/discount judgement is offered here.")

    fcf_y, div_y = rel.get("fcf_yield"), rel.get("dividend_yield")
    yields = (f"Free cash flow yield stands at {pct(fcf_y, 2)} and dividend yield at "
              f"{pct(div_y, 2)}. A low free-cash-flow yield alongside a high earnings multiple "
              "is the signature of a business reinvesting hard; it is a warning only if the "
              "reinvestment is not earning its cost of capital." if fcf_y is not None else "")

    peers = (
        "<b>No peer set was supplied with this run.</b> The methodology asks for three to five "
        "genuine comparables of similar size and business model, with P/E, ROCE and debt/equity "
        "for each. Without them this section compares the company against its own history only, "
        "which cannot tell you whether the whole sector has re-rated. Treat the relative "
        "conclusion as incomplete rather than as evidence of fair value, and weight Sections 5 "
        "and 6 accordingly. PEG, forward P/E and shareholder yield including buybacks are also "
        "absent from this data set and are not estimated.")

    return paras(placement, justify, yields, peers)


