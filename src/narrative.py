def build_narrative(result):
    """All eleven sections, keyed by section number as a string.

    A section that raises is caught and replaced with an explicit note rather
    than taking the whole report down: the computed tables in that panel are
    still worth rendering, and a missing paragraph is a smaller failure than a
    missing report.
    """
    out = {}
    for i, fn in _SECTIONS.items():
        try:
            out[str(i)] = fn(result)
        except Exception as exc:  # noqa: BLE001 - a bad paragraph must not lose the report
            out[str(i)] = (
                '<div class="callout warn"><span class="tag">Commentary unavailable</span>'
                f"This section's commentary could not be generated ({esc(exc)}). The computed "
                "figures below are unaffected.</div>")
    return out
