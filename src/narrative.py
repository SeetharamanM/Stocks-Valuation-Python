# 5 — Intrinsic Valuation
# ---------------------------------------------------------------------------

def s5(result):
    pack, a = result["pack"], result["assumptions"]
    d = pack["dcf"]

    if not d.get("viable"):
        return paras(
            "The primary cash-flow model could not be anchored, for the reason stated below. No "
            "substitute cash flow has been fabricated to force a number out of it, and the DCF "
            "carries no weight in the triangulation. The valuation therefore rests on the "
            "earnings- and asset-based methods in Section 7, which are more sensitive to the "
            "rating the market happens to apply today.",
            esc(a["rationale"].get("terminal_growth") or ""))

    tv_pct = d.get("terminal_value_pct")
    choice = (
        f"<b>Model choice: {esc(a.get('model_choice'))}.</b> A driver-based discounted cash flow "
        "is used because the business is valued on the cash it can generate rather than on the "
        "capital it holds. Each of the five explicit years is built from its own revenue growth, "
        "EBIT margin, tax rate, capex intensity and working-capital change, so a heavy "
        "investment year fades toward a steady state instead of being projected forever.")

    drivers_method = a["rationale"].get("drivers")
    drivers = (f"<b>How the driver path was set.</b> {esc(drivers_method)}"
               if drivers_method else
               "<b>How the driver path was set.</b> The forecast uses the drivers supplied to the "
               "model directly.")

    tg = f"<b>Terminal growth.</b> {esc(a['rationale'].get('terminal_growth') or '')}"

    rate = (
        f"<b>Discount rate.</b> Cost of equity is {pct(d.get('coe'))} on CAPM, using a "
        f"risk-free rate and equity risk premium supplied at run time and a beta of "
        f"{num(d.get('beta'), 2)}. Blended against post-tax cost of debt of "
        f"{pct(d.get('cost_of_debt_post_tax'))} at market weights, WACC comes to "
        f"{pct(d.get('wacc'))}. The pre-tax cost of debt is an assumed 9%, not a figure read "
        "from the statements — it is the least well-supported input in the discount rate.")

    if tv_pct is None:
        terminal = ""
    elif tv_pct > TERMINAL_VALUE_LIMIT:
        terminal = (
            f"<b>Where the value sits.</b> {pct(tv_pct)} of enterprise value is in the terminal "
            f"value, above the {pct(TERMINAL_VALUE_LIMIT)} threshold at which the methodology "
            "requires a flag. Most of this answer is therefore an assumption about the years "
            "beyond the forecast, not an analysis of the ones inside it. Section 7 reduces the "
            "DCF's weight for exactly this reason, and Section 10 shows how far the answer moves "
            "on a one-point change in the discount rate.")
    else:
        terminal = (f"<b>Where the value sits.</b> {pct(tv_pct)} of enterprise value is in the "
                    f"terminal value, within the {pct(TERMINAL_VALUE_LIMIT)} threshold. A "
                    "majority of the value is still an assumption about perpetuity — that is "
                    "true of every DCF — but the explicit forecast is carrying a meaningful "
                    "share of the answer.")

    ceiling_bits = []
    sgr, groic = d.get("sgr"), d.get("g_from_reinvestment")
    first_growth = None
    drivers_list = (d.get("assumptions") or {}).get("drivers") or []
    if drivers_list:
        first_growth = drivers_list[0].get("revenue_growth")
    if first_growth is not None and (sgr is not None or groic is not None):
        cands = [x for x in (sgr, groic) if x is not None]
        ceiling = min(cands)
        if abs(first_growth - ceiling) < 1e-6:
            ceiling_bits.append(
                f"<b>Growth cross-check.</b> The first forecast year assumes {pct(first_growth)} "
                f"revenue growth, which is exactly the self-funding ceiling of {pct(ceiling)} "
                f"(SGR {pct(sgr)}, reinvestment × ROIC {pct(groic)}) — the observed recent growth "
                "rate was above the ceiling and has been capped down to it. The forecast "
                "therefore assumes the company grows as fast as retained earnings allow and not "
                "one point faster, which is the most it can do without raising capital.")
        elif first_growth > ceiling:
            ceiling_bits.append(
                f"<b>Growth cross-check.</b> The first forecast year assumes {pct(first_growth)} "
                f"revenue growth against a self-funding ceiling of {pct(ceiling)} "
                f"(SGR {pct(sgr)}, reinvestment × ROIC {pct(groic)}). Growth above that ceiling "
                "has to be funded externally, which means dilution, more leverage, or a step-up "
                "in returns on capital. The model does not price any of those three, so this is "
                "the assumption to attack first.")
        else:
            ceiling_bits.append(
                f"<b>Growth cross-check.</b> The first forecast year assumes {pct(first_growth)} "
                f"revenue growth, within the self-funding ceiling of {pct(ceiling)} "
                f"(SGR {pct(sgr)}, reinvestment × ROIC {pct(groic)}). The forecast does not "
                "require external capital to be delivered.")

    return paras(choice, drivers, tg, rate, terminal, *ceiling_bits)


