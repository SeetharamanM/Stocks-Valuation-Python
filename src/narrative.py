# 4 — Historical Bands
# ---------------------------------------------------------------------------

def s4(result):
    b = result["pack"]["bands"]
    z, n = b.get("current_z"), len(b.get("pe_history") or [])
    med10, sd = b.get("median_pe_10y"), b.get("sd_pe")

    if z is None:
        where = ("The current multiple could not be placed within the historical band: either "
                 "the band or the current P/E is unavailable. The table below shows the "
                 "underlying series as far as it could be built.")
    elif z >= BAND_STRETCHED_SD:
        where = (f"The current P/E sits {num(z, 2)} standard deviations above the ten-year median "
                 f"of {mult(med10)}. On its own history the stock is expensively rated, and any "
                 "mean-reversion in the multiple works against the holder even if earnings "
                 "deliver exactly as forecast.")
    elif z <= -BAND_STRETCHED_SD:
        where = (f"The current P/E sits {num(abs(z), 2)} standard deviations below the ten-year "
                 f"median of {mult(med10)}. On its own history the stock is cheaply rated; the "
                 "question is whether the de-rating reflects a permanent change in the business.")
    else:
        where = (f"The current P/E sits {num(abs(z), 2)} standard deviations "
                 f"{'above' if z >= 0 else 'below'} the ten-year median of {mult(med10)} — "
                 "inside the ±1 SD band, so neither cheap nor stretched against its own record.")

    validity = (
        f"The band rests on {n} profitable years, with a standard deviation of {num(sd, 2)} "
        f"turns of earnings. " +
        ("A series this short is a weak anchor: a single re-rating year moves the median, and "
         "mean reversion to it is an assumption rather than a finding. "
         if n < 7 else
         "That is enough history for the median to mean something, provided the business has not "
         "structurally changed over the period. ") +
        "Loss-making years are excluded from the series entirely, because a negative P/E is not a "
        "rating; where a company has had them, the band describes only its profitable phases.")

    caveat = (
        "This model does not attempt to detect the year of a re-rating or attribute a cause to "
        "it, which the methodology asks for. That is a judgement about the business, and it "
        "requires source material this tool does not read. Where the chart below shows an "
        "obvious step change, the pre-step years should be discounted by hand."
        if n else "")

    return paras(where, validity, caveat)


